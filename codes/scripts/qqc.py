#!/usr/bin/env python3
"""Quantum codes from Hermitian self-orthogonal quasi-cyclic GF(4) codes.

If the cyclic code <g> of length l over GF(4) is Hermitian self-orthogonal
(g * conj(g)^* = 0 mod x^l - 1, ^* = reciprocal), then for any f_1..f_m the
quasi-cyclic code C generated by (g f_1, ..., g f_m) is Hermitian
self-orthogonal too.  C = [m*l, kappa = l - deg g]_4 gives the stabilizer code
[[m*l, m*l - 2*kappa, d = wt(C^perp_h \\ C)]].

GF(4)-linear code -> additive (symplectic) code: element a + b*w (canonical
index a + 2b) maps each codeword c to the two binary vectors of c and w*c, and
the trace-Hermitian form becomes the symplectic one with
    GF(4) element -> (x, z) bits: 0->(0,0), 1->(1,1), w->(0,1), w^2->(1,0)
(any fixed GF(2)-linear isomorphism matching trace-Hermitian to symplectic).

usage: qqc.py n k [--secs S] [--seed s]
"""
import argparse
import json
import random
import sys
import time

import numpy as np

from gf import GF, ROOT
from poly import PolyRing
from qsearch import load_qbounds
from quantum import normalizer, qdist, rank, sym

F4 = GF(4)
R4 = PolyRing(4)
CONJ = [0, 1, 3, 2]          # Frobenius a -> a^2 on canonical indices (w <-> w^2 = w+1)
# symplectic image of GF(4) elements: chosen so that symplectic product = trace-Hermitian product
TO_XZ = {0: (0, 0), 1: (1, 1), 2: (0, 1), 3: (1, 0)}


def conj_rev(p, l):
    """conj(p)(x^{-1}) mod x^l - 1 as coefficient list of length l."""
    out = [0] * l
    for i, c in enumerate(p):
        if c:
            out[(-i) % l] = CONJ[c]
    return R4.trim(out)


def mulmod(a, b, l):
    r = R4.mul(a, b)
    out = [0] * l
    for i, c in enumerate(r):
        out[i % l] = F4.add[out[i % l], c]
    return R4.trim(out)


def herm_self_orth_cyclic(g, l):
    return not mulmod(g, conj_rev(g, l), l)


def to_symplectic(G):
    """Rows of a GF(4) generator matrix -> symplectic generators of the additive code (c, w*c)."""
    gens = []
    for row in G:
        for scal in (1, 2):
            x = z = 0
            for i, c in enumerate(row):
                e = int(F4.mul[scal, c])
                bx, bz = TO_XZ[e]
                x |= bx << i
                z |= bz << i
            gens.append((x, z))
    return gens


def self_orth_divisors(l):
    """All divisors g of x^l - 1 over GF(4) with <g> Hermitian self-orthogonal, by degree."""
    facs = R4.factor_squarefree(R4.x_n_minus(l, 1))
    out = {}
    nf = len(facs)
    if nf > 18:
        raise ValueError("too many factors")
    for mask in range(1 << nf):
        g = [1]
        for i in range(nf):
            if mask >> i & 1:
                g = R4.mul(g, facs[i])
        if herm_self_orth_cyclic(g, l):
            out.setdefault(len(g) - 1, []).append(g)
    return out


def qc_generator(g, fs, l):
    k = l - (len(g) - 1)
    blocks = []
    for f in fs:
        a = mulmod(g, f, l)
        a = a + [0] * (l - len(a))
        rows = []
        v = list(a)
        for _ in range(k):
            rows.append(v)
            v = [v[-1]] + v[:-1]
        blocks.append(np.array(rows, np.uint8))
    return np.hstack(blocks)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("n", type=int)
    ap.add_argument("k", type=int)
    ap.add_argument("--secs", type=float, default=300)
    ap.add_argument("--seed", type=int, default=int(time.time()))
    args = ap.parse_args()
    n, k = args.n, args.k
    B = load_qbounds()
    lo, hi = B[(n, k)]
    T = lo + 1
    rng = random.Random(args.seed)
    options = []
    for m in range(2, 9):
        if n % m or (n // m) % 2 == 0:
            continue
        l = n // m
        kappa = (n - k) // 2
        if (n - k) % 2 or kappa > l:
            continue
        try:
            divs = self_orth_divisors(l)
        except ValueError:
            continue
        gs = divs.get(l - kappa, [])
        if gs:
            options.append((m, l, gs))
    if not options:
        print(f"[[{n},{k}]]: no self-orthogonal QC option", file=sys.stderr)
        return
    t0 = time.time()
    tried = 0
    best = 0
    out = ROOT / "results" / "qcandidates.jsonl"
    while time.time() - t0 < args.secs:
        m, l, gs = rng.choice(options)
        g = rng.choice(gs)
        kappa = l - (len(g) - 1)
        fs = [[1]] + [[rng.randrange(4) for _ in range(l)] for _ in range(m - 1)]
        G = qc_generator(g, fs, l)
        S = to_symplectic(G)
        if rank(S, n) != n - k:
            continue
        tried += 1
        N = normalizer(S, n)
        d = qdist(N, n, target=T, threads=1, exclude=S)
        if d >= T:
            assert all(sym(a, b) == 0 for a in S for b in S)
            d = qdist(N, n, threads=1, exclude=S)
            rec = dict(n=n, k=k, d=d, table=[lo, hi], family="herm-QC", m=m, l=l, g=g, fs=fs,
                       stab=[list(v) for v in S], time=time.time())
            with open(out, "a") as f:
                f.write(json.dumps(rec) + "\n")
            print(f"*** QUANTUM CANDIDATE [[{n},{k},{d}]] (table {lo}-{hi}) m={m} l={l}", flush=True)
    print(f"[[{n},{k}]] herm-QC: tried {tried}, {time.time()-t0:.0f}s, options "
          f"{[(m, l, len(gs)) for m, l, gs in options]}", file=sys.stderr, flush=True)


if __name__ == "__main__":
    main()
