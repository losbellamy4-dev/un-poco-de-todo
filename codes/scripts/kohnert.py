#!/usr/bin/env python3
"""Codes with a prescribed automorphism group (Braun-Kohnert-Wassermann style) via MIP.

A projective [n, k, d]_q code  <=>  n points of PG(k-1, q) with at most
m = n - d of them on every hyperplane.  Prescribing a group G <= GL(k, q):
the point set is a union of G-orbits O_i, and it suffices to check one
hyperplane per G-orbit.  This gives the 0/1 program
    sum_i |O_i| x_i = n,      sum_i |O_i cap H_j| x_i <= m   (every hyperplane orbit rep H_j)
solved with HiGHS.  Groups: cyclic <A>, A random in GL(k, q) (optionally a power of it
to reach a target order).  Multiplicities are allowed with --mult (x_i in 0..mult).

usage: kohnert.py q k n d [--secs S] [--tries T] [--ordmin a --ordmax b] [--seed s]
"""
import argparse
import json
import random
import sys
import time

import highspy
import numpy as np

from gf import GF, ROOT, min_distance


class Geometry:
    def __init__(self, q, k):
        self.q, self.k = q, k
        F = self.F = GF(q)
        pts = []
        for t in range(1, q ** k):
            v, x = [], t
            for _ in range(k):
                v.append(x % q)
                x //= q
            top = max(i for i in range(k) if v[i])
            if v[top] == 1:
                pts.append(tuple(v))
        self.pts = pts
        self.index = {p: i for i, p in enumerate(pts)}
        P = np.array(pts, np.uint8)                     # P x k
        # incidence[h, p] = <h, p> == 0
        dots = np.zeros((len(pts), len(pts)), np.uint8)
        for i in range(k):
            dots = F.add[dots, F.mul[P[:, i][:, None], P[:, i][None, :]]]
        self.inc = (dots == 0)
        self.P = P

    def normalize(self, v):
        F = self.F
        top = max(i for i in range(self.k) if v[i])
        s = int(F.inv[v[top]])
        return tuple(int(F.mul[s, x]) for x in v)

    def act(self, A, v):
        F = self.F
        out = [0] * self.k
        for i in range(self.k):
            s = 0
            for j in range(self.k):
                s = int(F.add[s, F.mul[A[i][j], v[j]]])
            out[i] = s
        return self.normalize(out)

    def orbits_multi(self, gens):
        """Orbits under the group generated by several matrices (union-find)."""
        P = len(self.pts)
        parent = list(range(P))

        def find(a):
            while parent[a] != a:
                parent[a] = parent[parent[a]]
                a = parent[a]
            return a
        for A in gens:
            for i, p in enumerate(self.pts):
                j = self.index[self.act(A, p)]
                ri, rj = find(i), find(j)
                if ri != rj:
                    parent[ri] = rj
        groups = {}
        for i in range(P):
            groups.setdefault(find(i), []).append(i)
        orbs = list(groups.values())
        seen = [0] * P
        for c, o in enumerate(orbs):
            for i in o:
                seen[i] = c
        return orbs, seen

    def orbits(self, A):
        if isinstance(A, tuple):
            return self.orbits_multi(list(A))
        seen = [-1] * len(self.pts)
        orbs = []
        for i, p in enumerate(self.pts):
            if seen[i] >= 0:
                continue
            orb, cur = [], p
            while True:
                j = self.index[cur]
                if seen[j] >= 0:
                    break
                seen[j] = len(orbs)
                orb.append(j)
                cur = self.act(A, cur)
            orbs.append(orb)
        return orbs, seen


def mat_inv_T(F, A, k):
    """(A^-1)^T over GF(q) by Gauss-Jordan."""
    M = [list(A[i]) + [1 if i == j else 0 for j in range(k)] for i in range(k)]
    for c in range(k):
        p = next(r for r in range(c, k) if M[r][c])
        M[c], M[p] = M[p], M[c]
        iv = int(F.inv[M[c][c]])
        M[c] = [int(F.mul[iv, x]) for x in M[c]]
        for r in range(k):
            if r != c and M[r][c]:
                f = M[r][c]
                M[r] = [int(F.sub[x, F.mul[f, y]]) for x, y in zip(M[r], M[c])]
    inv = [row[k:] for row in M]
    return [[inv[j][i] for j in range(k)] for i in range(k)]


def random_gl(F, q, k, rng):
    while True:
        A = [[rng.randrange(q) for _ in range(k)] for _ in range(k)]
        if F.rank(np.array(A, np.uint8)) == k:
            return A


def mat_mul(F, A, B, k):
    return [[int(np.bitwise_xor.reduce([0])) for _ in range(k)] for _ in range(k)] if False else \
        [[_dot(F, A[i], [B[t][j] for t in range(k)]) for j in range(k)] for i in range(k)]


def _dot(F, a, b):
    s = 0
    for x, y in zip(a, b):
        s = int(F.add[s, F.mul[x, y]])
    return s


def prime_factors(x):
    out, p = [], 2
    while p * p <= x:
        while x % p == 0:
            if p not in out:
                out.append(p)
            x //= p
        p += 1
    if x > 1:
        out.append(x)
    return out


def frobenius_matrix(q, k, f):
    """Matrix of a -> a^q on GF(q)[x]/(f) in the basis 1, x, ..., x^(k-1) (columns)."""
    from poly import PolyRing
    R = PolyRing(q)
    M = [[0] * k for _ in range(k)]
    for j in range(k):
        col = R.powmod([0, 1], j * q, f) if j else [1]
        for i, c in enumerate(col):
            M[i][j] = c
    return M


def singer_matrix(q, k, rng, return_poly=False):
    """Companion matrix of a random primitive polynomial of degree k over GF(q)."""
    from poly import PolyRing
    R = PolyRing(q)
    N = q ** k - 1
    pf = prime_factors(N)
    while True:
        f = [rng.randrange(q) for _ in range(k)] + [1]
        if f[0] == 0:
            continue
        if all(R.powmod([0, 1], N // p, f) != [1] for p in pf) and R.powmod([0, 1], N, f) == [1]:
            break
    F = GF(q)
    C = [[0] * k for _ in range(k)]
    for i in range(1, k):
        C[i][i - 1] = 1
    for i in range(k):
        C[i][k - 1] = int(F.neg[f[i]])
    return (C, f) if return_poly else C


def mat_pow(F, A, e, k):
    R = [[int(i == j) for j in range(k)] for i in range(k)]
    B = A
    while e:
        if e & 1:
            R = mat_mul(F, R, B, k)
        B = mat_mul(F, B, B, k)
        e >>= 1
    return R


def solve(geo, A, n, m, mult, secs):
    orbs, _ = geo.orbits(A)
    if isinstance(A, tuple):
        AT = tuple(mat_inv_T(geo.F, B, geo.k) for B in A)
    else:
        AT = mat_inv_T(geo.F, A, geo.k)
    horbs, _ = geo.orbits(AT)
    reps = [o[0] for o in horbs]
    sizes = [len(o) for o in orbs]
    # coefficient matrix: points of orbit i on hyperplane rep j
    rows = []
    for h in reps:
        row = [int(geo.inc[h, o].sum()) for o in orbs]
        rows.append(row)
    h = highspy.Highs()
    h.setOptionValue("output_flag", False)
    h.setOptionValue("time_limit", float(secs))
    inf = highspy.kHighsInf
    nv = len(orbs)
    for i in range(nv):
        h.addVar(0, mult)
        h.changeColIntegrality(i, highspy.HighsVarType.kInteger)
    h.addRow(n, n, nv, np.arange(nv, dtype=np.int32), np.array(sizes, np.float64))
    for row in rows:
        idx = np.array([i for i, c in enumerate(row) if c], np.int32)
        val = np.array([row[i] for i in idx], np.float64)
        if len(idx):
            h.addRow(-inf, m, len(idx), idx, val)
    h.run()
    st = h.getModelStatus()
    if st != highspy.HighsModelStatus.kOptimal:
        return None, len(orbs), str(st)
    x = h.getSolution().col_value
    cols = []
    for i, o in enumerate(orbs):
        c = int(round(x[i]))
        for _ in range(c):
            cols += [geo.pts[j] for j in o]
    return np.array(cols, np.uint8).T, len(orbs), "ok"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("q", type=int)
    ap.add_argument("k", type=int)
    ap.add_argument("n", type=int)
    ap.add_argument("d", type=int)
    ap.add_argument("--secs", type=float, default=600)
    ap.add_argument("--mip-secs", type=float, default=30)
    ap.add_argument("--ordmin", type=int, default=5)
    ap.add_argument("--ordmax", type=int, default=200)
    ap.add_argument("--mult", type=int, default=1)
    ap.add_argument("--seed", type=int, default=int(time.time()))
    ap.add_argument("--singer", type=float, default=0.3, help="fraction of groups taken from a Singer cycle")
    ap.add_argument("--frob", type=float, default=0.3, help="fraction of groups <Singer^e, Frobenius>")
    args = ap.parse_args()
    q, k, n, d = args.q, args.k, args.n, args.d
    m = n - d
    rng = random.Random(args.seed)
    geo = Geometry(q, k)
    t0 = time.time()
    tries = 0
    P = len(geo.pts)
    # a Singer cycle acts regularly on the P points; its subgroup of order t has all orbits of size t,
    # so only t | n can work: use C^(P/t) for such t
    singer_exps = [P // t for t in range(2, P + 1) if P % t == 0 and n % t == 0 and t <= args.ordmax * 10]
    while time.time() - t0 < args.secs:
        u = rng.random()
        if u < args.frob:
            C, f = singer_matrix(q, k, rng, return_poly=True)
            e = rng.choice([P // t for t in range(1, P + 1) if P % t == 0 and t <= args.ordmax * 10])
            A = (mat_pow(geo.F, C, e, k), frobenius_matrix(q, k, f))
            tries += 1
            G, norb, status = solve(geo, A, n, m, args.mult, args.mip_secs)
            if G is not None:
                dd = min_distance(q, G)
                print(f"*** FOUND [{n},{k},{dd}]_{q} with {norb} orbits (asked d>={d}) [Singer^e x Frobenius]",
                      flush=True)
                rec = dict(q=q, n=n, k=k, d_lower_bound=dd, kind="matrix", G=G.tolist(),
                           origin=dict(kind="prescribed-group(Singer,Frobenius)+MIP", A=[list(map(list, B)) for B in A]),
                           time=time.time())
                with open(ROOT / "results" / "candidates.jsonl", "a") as fo:
                    fo.write(json.dumps(rec) + "\n")
                break
            continue
        if singer_exps and u < args.frob + args.singer:
            A = mat_pow(geo.F, singer_matrix(q, k, rng), rng.choice(singer_exps), k)
        else:
            A = random_gl(geo.F, q, k, rng)
        orbs, _ = geo.orbits(A)
        sizes = sorted(set(len(o) for o in orbs))
        order = max(sizes)
        if not (args.ordmin <= order <= args.ordmax):
            # try a power of A with smaller order
            divs = [e for e in range(2, order) if order % e == 0 and args.ordmin <= order // e <= args.ordmax]
            if not divs:
                continue
            e = rng.choice(divs)
            B = A
            for _ in range(e - 1):
                B = mat_mul(geo.F, B, A, k)
            A = B
        tries += 1
        G, norb, status = solve(geo, A, n, m, args.mult, args.mip_secs)
        if G is None:
            continue
        dd = min_distance(q, G)
        print(f"*** FOUND [{n},{k},{dd}]_{q} with {norb} orbits (asked d>={d})", flush=True)
        rec = dict(q=q, n=n, k=k, d_lower_bound=dd, kind="matrix", G=G.tolist(),
                   origin=dict(kind="prescribed-cyclic-group+MIP", A=A), time=time.time())
        with open(ROOT / "results" / "candidates.jsonl", "a") as f:
            f.write(json.dumps(rec) + "\n")
        break
    print(f"[{n},{k},{d}]_{q}: {tries} groups tried in {time.time()-t0:.0f}s", file=sys.stderr, flush=True)


if __name__ == "__main__":
    main()
