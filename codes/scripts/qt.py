"""Quasi-twisted (QT) codes and helpers.

A 1-generator QT code of index m and co-index l over GF(q) with shift constant
lam is generated by (g*f_1, ..., g*f_m) in (F[x]/(x^l - lam))^m with
g | x^l - lam, deg g = l - k.  Taking f_1 = 1 gives dimension exactly k.
"""
import math
import random

import numpy as np

from gf import GF
from poly import PolyRing


def load_bounds(q):
    from gf import ROOT
    B = {}
    with open(ROOT / "data" / f"bounds_q{q}.tsv") as f:
        next(f)
        for line in f:
            n, k, lo, hi = map(int, line.split())
            B[(n, k)] = (lo, hi)
    return B


def bz_cost(q, n, k, d):
    """Rough number of codewords Brouwer-Zimmermann enumerates to prove d(C) >= d."""
    m, rest = divmod(n, k)
    ranks = [k] * m + ([rest] if rest else [])
    total = 0.0
    for w in range(1, k + 1):
        lb = sum(max(0, w + 1 - (k - r)) for r in ranks)
        total += math.comb(k, w) * (q - 1) ** (w - 1) * sum(1 for r in ranks if w + 1 > k - r)
        if lb >= d:
            return total
    return total


def constashift_rows(F, a, l, lam, k):
    """Rows x^i * a mod (x^l - lam), i = 0..k-1, as a (k x l) uint8 array."""
    rows = np.zeros((k, l), np.uint8)
    v = np.zeros(l, np.uint8)
    v[: len(a)] = a
    for i in range(k):
        rows[i] = v
        last = v[-1]
        v = np.roll(v, 1)
        v[0] = F.mul[lam, last]
    return rows


class QTFamily:
    """Factorisation data for x^l - lam over GF(q)."""

    def __init__(self, q, l, lam, seed=0):
        self.q, self.l, self.lam = q, l, lam
        self.R = PolyRing(q)
        self.F = GF(q)
        self.factors = self.R.factor_squarefree(self.R.x_n_minus(l, lam), seed)
        self.degs = [len(f) - 1 for f in self.factors]
        # achievable divisor degrees (subset sums)
        reach = {0}
        for d in self.degs:
            reach |= {r + d for r in reach}
        self.reach = reach

    def random_divisor(self, deg, rng, tries=500):
        """Random monic divisor of x^l - lam of the given degree (or None)."""
        if deg not in self.reach:
            return None
        idx = list(range(len(self.factors)))
        for _ in range(tries):
            rng.shuffle(idx)
            tot, pick = 0, []
            for i in idx:
                if tot + self.degs[i] <= deg:
                    pick.append(i)
                    tot += self.degs[i]
                    if tot == deg:
                        break
            if tot == deg:
                g = [1]
                for i in pick:
                    g = self.R.mul(g, self.factors[i])
                return g
        return None

    def generator(self, g, fs, k):
        """Generator matrix k x (m*l) for (g*f_1,...,g*f_m)."""
        blocks = []
        modulus = self.R.x_n_minus(self.l, self.lam)
        for f in fs:
            a = self.R.mod(self.R.mul(g, f), modulus)
            blocks.append(constashift_rows(self.F, a, self.l, self.lam, k))
        return np.hstack(blocks)
